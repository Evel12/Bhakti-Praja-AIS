import { launch, shot, sleep, clickText } from './lib.mjs';
const b = await launch();
const base = 'http://127.0.0.1:4173/';
const page = await b.newPage();
await page.goto(base + '#/login', { waitUntil: 'networkidle0' });
await sleep(800);
await Promise.all([page.click('button[type=submit]'), sleep(2500)]);
const dump = async (label) => console.log(label, JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('main button, main a, main input, main textarea, main select')].filter((e) => e.offsetParent).map((e) => (e.tagName + ':' + (e.innerText || e.placeholder || e.name || e.type || '')).replace(/\s+/g, ' ').slice(0, 40))), null, 0), page.url());
await clickText(page, 'Buat assessment');
await sleep(1200);
await page.type('input[placeholder^="Contoh"]', 'Evaluasi Basis Data & SQL Dasar');
await page.type('textarea', 'Kuis pemahaman dasar perintah SQL (SELECT, INSERT, UPDATE, DELETE).');
await clickText(page, 'Lanjutkan');
await sleep(1200);
await shot(page, '_b-builder2');
await dump('step2');
await page.evaluate(() => window.scrollTo(0, 99999));
await shot(page, '_b-builder2b', { full: true });
await clickText(page, 'Pilih dari bank soal').catch((e) => console.log(e.message));
await sleep(800);
await shot(page, '_b-bankmodal');
await dump('bankmodal');
await b.close();
